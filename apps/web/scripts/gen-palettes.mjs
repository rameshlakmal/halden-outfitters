const c = ([l, ch, h]) => `oklch(${l} ${ch} ${h})`;
function tokens(t, indent) {
  const pad = ' '.repeat(indent);
  return [
    `--bg: ${c(t.bg)};`, `--surface: ${c(t.surface)};`, `--surface-2: ${c(t.s2)};`, `--surface-3: ${c(t.s3)};`,
    `--ink: ${c(t.ink)};`, `--ink-2: ${c(t.ink2)};`, `--ink-3: ${c(t.ink3)};`, `--line: ${c(t.line)};`,
    `--line-strong: ${c(t.ink)};`, `--brand: ${c(t.ink)};`, `--brand-ink: ${c(t.bg)};`, `--brand-soft: ${c(t.soft)};`,
    `--accent: ${c(t.accent)};`, `--accent-hover: ${c(t.accentHover)};`, `--accent-ink: ${c(t.accentInk)};`,
    `--glass: oklch(${t.bg[0]} ${t.bg[1]} ${t.bg[2]} / 0.88);`,
  ].map((l) => pad + l).join('\n');
}

let css = '/* Generated by scripts/gen-palettes.mjs. Alpine preview palettes; "signal" is the default in globals.css. */\n\n';
for (const [id, p] of Object.entries(P)) {
  const sel = `:root[data-palette='${id}']`;
  if (p.darkByDefault) {
    // Dark unless the visitor picked light.
    css += `${sel} {\n  color-scheme: dark;\n${tokens(p.dark, 2)}\n}\n${sel}[data-theme='light'] {\n  color-scheme: light;\n${tokens(p.light, 2)}\n}\n\n`;
  } else {
    css += `${sel} {\n  color-scheme: light;\n${tokens(p.light, 2)}\n}\n@media (prefers-color-scheme: dark) {\n  ${sel}:not([data-theme='light']) {\n    color-scheme: dark;\n${tokens(p.dark, 4)}\n  }\n}\n${sel}[data-theme='dark'] {\n  color-scheme: dark;\n${tokens(p.dark, 2)}\n}\n\n`;
  }
}
writeFileSync(new URL('../app/palettes.css', import.meta.url), css);
